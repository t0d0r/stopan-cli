// Shell completion scripts, generated from the command table so they
// follow every new command and option (specs/completion.md).

var shells = []string{"bash", "zsh", "fish"}

// The completion command is added here, not in the table, since its
// script is generated from the table.
func init() {
	commands = append(commands, command{
		name:     "completion",
		synopsis: "SHELL",
		summary:  "print the shell completion script",
		about: `
Print the completion script for SHELL: bash, zsh or fish. It completes
commands, options, views, statuses, priorities and profile names.

  bash  source <(stopan completion bash)          (in ~/.bashrc)
  zsh   stopan completion zsh > "${fpath[1]}/_stopan"
  fish  stopan completion fish > ~/.config/fish/completions/stopan.fish

Homebrew and the .deb package install the scripts already.`,
		permute: true,
		setup: func(f *flagDefs) action {
			return func(e env, args []string) error {
				if len(args) != 1 {
					return usagef("give one shell: bash, zsh or fish")
				}
				return writeCompletion(e.out, args[0])
			}
		},
	})
}

// compCmd is one command as the completion scripts see it.
type compCmd struct {
	name    string
	names   []string // name and aliases
	summary string
	opts    []optDoc
	first   string // what the first argument is: "view", "profile", "shell", "command" or ""
}

func compCommands() []compCmd {
	var out []compCmd
	for _, c := range commands {
		f := newFlagDefs(c.name)
		c.setup(f)
		addProfileOption(f)
		first := map[string]string{"list": "view", "use": "profile", "completion": "shell"}[c.name]
		out = append(out, compCmd{c.name, append([]string{c.name}, c.aliases...), c.summary, f.opts, first})
	}
	return append(out, compCmd{name: "help", names: []string{"help"}, summary: "show help for a command", first: "command"})
}

// optValues are the fixed values of an option argument, by long name;
// "profile" is filled in at completion time. nil: free text.
func optValues(long string) []string {
	views := append(append([]string{}, api.StaffViews...), "open")
	return map[string][]string{
		"view":     views,
		"status":   api.Statuses,
		"priority": api.Priorities,
		"sort":     api.Sorts,
		"assignee": {"me", "none"},
	}[long]
}

func firstValues(kind string) []string {
	switch kind {
	case "view":
		return optValues("view")
	case "shell":
		return shells
	case "command":
		var names []string
		for _, c := range compCommands() {
			names = append(names, c.name)
		}
		return names
	}
	return nil
}

// profileNames is the shell command that lists the saved profiles.
const profileNames = "stopan profiles --names 2>/dev/null"

var globalOpts = []optDoc{
	{short: "P", long: "profile", arg: "NAME", help: "use this profile"},
	{short: "h", long: "help", help: "show help"},
	{short: "V", long: "version", help: "print the version"},
}

func flags(o optDoc) []string {
	var s []string
	if o.short != "" {
		s = append(s, "-"+o.short)
	}
	return append(s, "--"+o.long)
}

func allFlags(opts []optDoc) []string {
	var s []string
	for _, o := range opts {
		s = append(s, flags(o)...)
	}
	return append(s, "-h", "--help")
}

func writeCompletion(w io.Writer, shell string) error {
	switch shell {
	case "bash":
		writeBash(w)
	case "zsh":
		writeZsh(w)
	case "fish":
		writeFish(w)
	default:
		return usagef("unknown shell %q; use bash, zsh or fish", shell)
	}
	return nil
}

// Bash.

func writeBash(w io.Writer) {
	var cmds []string
	for _, c := range compCommands() {
		cmds = append(cmds, c.name)
	}
	fmt.Fprintf(w, `# bash completion for stopan; generated by 'stopan completion bash'
_stopan() {
    local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}
    local cmd= cmdi=0 i
    for ((i = 1; i < COMP_CWORD; i++)); do
        case ${COMP_WORDS[i]} in
            -P|--profile) ((i++)) ;;
            -*) ;;
            *) cmd=${COMP_WORDS[i]} cmdi=$i; break ;;
        esac
    done
    COMPREPLY=()
    case $prev in
        -P|--profile) COMPREPLY=($(compgen -W "$(%s)" -- "$cur")); return ;;
    esac
    case $cmd in
        '')
            if [[ $cur == -* ]]; then
                COMPREPLY=($(compgen -W %q -- "$cur"))
            else
                COMPREPLY=($(compgen -W %q -- "$cur"))
            fi
            return ;;
`, profileNames, strings.Join(allFlags(globalOpts[:1]), " ")+" -V --version", strings.Join(cmds, " "))
	for _, c := range compCommands() {
		fmt.Fprintf(w, "        %s)\n", strings.Join(c.names, "|"))
		var cases []string
		for _, o := range c.opts {
			if o.arg == "" || o.long == "profile" {
				continue
			}
			vals := ""
			if v := optValues(o.long); v != nil {
				vals = fmt.Sprintf("COMPREPLY=($(compgen -W %q -- \"$cur\")); ", strings.Join(v, " "))
			}
			cases = append(cases, fmt.Sprintf("                %s) %sreturn ;;\n", strings.Join(flags(o), "|"), vals))
		}
		if len(cases) > 0 {
			fmt.Fprintf(w, "            case $prev in\n%s            esac\n", strings.Join(cases, ""))
		}
		fmt.Fprintf(w, "            if [[ $cur == -* ]]; then\n                COMPREPLY=($(compgen -W %q -- \"$cur\"))\n", strings.Join(allFlags(c.opts), " "))
		switch c.first {
		case "profile":
			fmt.Fprintf(w, "            elif ((COMP_CWORD == cmdi + 1)); then\n                COMPREPLY=($(compgen -W \"$(%s)\" -- \"$cur\"))\n", profileNames)
		case "":
		default:
			fmt.Fprintf(w, "            elif ((COMP_CWORD == cmdi + 1)); then\n                COMPREPLY=($(compgen -W %q -- \"$cur\"))\n", strings.Join(firstValues(c.first), " "))
		}
		fmt.Fprint(w, "            fi ;;\n")
	}
	fmt.Fprint(w, `    esac
}
complete -F _stopan stopan
`)
}

// Zsh.

// zshDescribe offers NAME:DESCRIPTION items with _describe. Names
// escape ':'; both are quoted for zsh single quotes.
func zshDescribe(tag string, items [][2]string) string {
	q := func(s string) string { return strings.ReplaceAll(s, "'", `'\''`) }
	var parts []string
	for _, it := range items {
		parts = append(parts, "'"+q(strings.ReplaceAll(it[0], ":", `\:`))+":"+q(it[1])+"'")
	}
	return "local -a items=(" + strings.Join(parts, " ") + "); _describe " + tag + " items"
}

func optItems(opts []optDoc) [][2]string {
	var items [][2]string
	for _, o := range opts {
		for _, f := range flags(o) {
			items = append(items, [2]string{f, o.help})
		}
	}
	return append(items, [2]string{"-h", "show help"}, [2]string{"--help", "show help"})
}

func writeZsh(w io.Writer) {
	var cmdItems [][2]string
	for _, c := range compCommands() {
		cmdItems = append(cmdItems, [2]string{c.name, c.summary})
	}
	globals := append(optItems(globalOpts[:1]), [2]string{"-V", "print the version"}, [2]string{"--version", "print the version"})
	fmt.Fprintf(w, `#compdef stopan
# zsh completion for stopan; generated by 'stopan completion zsh'
_stopan() {
    local cur=${words[CURRENT]} prev=${words[CURRENT-1]}
    local cmd= cmdi=0 i
    for ((i = 2; i < CURRENT; i++)); do
        case ${words[i]} in
            -P|--profile) ((i++)) ;;
            -*) ;;
            *) cmd=${words[i]} cmdi=$i; break ;;
        esac
    done
    case $prev in
        -P|--profile) compadd -- ${(f)"$(%s)"}; return ;;
    esac
    case $cmd in
        '')
            if [[ $cur == -* ]]; then
                %s
            else
                %s
            fi
            return ;;
`, profileNames, zshDescribe("option", globals), zshDescribe("command", cmdItems))
	for _, c := range compCommands() {
		fmt.Fprintf(w, "        %s)\n", strings.Join(c.names, "|"))
		var cases []string
		for _, o := range c.opts {
			if o.arg == "" || o.long == "profile" {
				continue
			}
			vals := ""
			if v := optValues(o.long); v != nil {
				vals = "compadd -- " + strings.Join(v, " ") + "; "
			}
			cases = append(cases, fmt.Sprintf("                %s) %sreturn ;;\n", strings.Join(flags(o), "|"), vals))
		}
		if len(cases) > 0 {
			fmt.Fprintf(w, "            case $prev in\n%s            esac\n", strings.Join(cases, ""))
		}
		fmt.Fprintf(w, "            if [[ $cur == -* ]]; then\n                %s\n", zshDescribe("option", optItems(c.opts)))
		switch c.first {
		case "profile":
			fmt.Fprintf(w, "            elif ((CURRENT == cmdi + 1)); then\n                compadd -- ${(f)\"$(%s)\"}\n", profileNames)
		case "":
		default:
			fmt.Fprintf(w, "            elif ((CURRENT == cmdi + 1)); then\n                compadd -- %s\n", strings.Join(firstValues(c.first), " "))
		}
		fmt.Fprint(w, "            fi ;;\n")
	}
	fmt.Fprint(w, `    esac
}
if [[ $funcstack[1] == _stopan ]]; then
    _stopan "$@"
else
    compdef _stopan stopan
fi
`)
}

// Fish.

func fq(s string) string {
	return "'" + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), "'", `\'`) + "'"
}

func writeFish(w io.Writer) {
	fmt.Fprint(w, `# fish completion for stopan; generated by 'stopan completion fish'
complete -c stopan -f
`)
	prof := fq("(" + profileNames + ")")
	fmt.Fprintf(w, "complete -c stopan -s P -l profile -x -a %s -d %s\n", prof, fq("use this profile"))
	fmt.Fprintf(w, "complete -c stopan -n __fish_use_subcommand -s V -l version -d %s\n", fq("print the version"))
	fmt.Fprintf(w, "complete -c stopan -s h -l help -d %s\n", fq("show help"))
	for _, c := range compCommands() {
		fmt.Fprintf(w, "complete -c stopan -n __fish_use_subcommand -a %s -d %s\n", c.name, fq(c.summary))
	}
	for _, c := range compCommands() {
		cond := fq("__fish_seen_subcommand_from " + strings.Join(c.names, " "))
		for _, o := range c.opts {
			if o.long == "profile" {
				continue
			}
			line := "complete -c stopan -n " + cond
			if o.short != "" {
				line += " -s " + o.short
			}
			line += " -l " + o.long
			if o.arg != "" {
				line += " -x"
				if v := optValues(o.long); v != nil {
					line += " -a " + fq(strings.Join(v, " "))
				}
			}
			fmt.Fprintln(w, line+" -d "+fq(o.help))
		}
		switch c.first {
		case "profile":
			fmt.Fprintf(w, "complete -c stopan -n %s -a %s\n", cond, prof)
		case "":
		default:
			fmt.Fprintf(w, "complete -c stopan -n %s -a %s\n", cond, fq(strings.Join(firstValues(c.first), " ")))
		}
	}
}
